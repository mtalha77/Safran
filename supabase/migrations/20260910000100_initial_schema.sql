create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = (select auth.uid())
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name'),
    new.raw_user_meta_data ->> 'phone'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.role is distinct from old.role
    and coalesce((select auth.role()), 'service_role') <> 'service_role'
    and not public.is_admin()
  then
    raise exception 'Only administrators may change profile roles';
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role
  before update on public.profiles
  for each row execute function public.protect_profile_role();

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'profiles',
    'menu_categories',
    'menu_items',
    'site_settings',
    'content_blocks',
    'opening_hours',
    'store_availability',
    'orders'
  ]
  loop
    execute format('drop trigger if exists set_%I_updated_at on public.%I', table_name, table_name);
    execute format(
      'create trigger set_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()',
      table_name,
      table_name
    );
  end loop;
end $$;

create or replace view public.store_settings
with (security_invoker = true)
as
select
  'default'::text as id,
  coalesce((select value #>> '{}' from public.site_settings where key = 'restaurant_name'), 'Safran') as restaurant_name,
  (select value #>> '{}' from public.site_settings where key = 'contact_email') as email,
  (select value #>> '{}' from public.site_settings where key = 'contact_phone') as phone,
  (select value #>> '{}' from public.site_settings where key = 'address') as address,
  coalesce((select (value #>> '{}')::numeric from public.site_settings where key = 'delivery_minimum'), 0) as minimum_order,
  coalesce((select (value #>> '{}')::numeric from public.site_settings where key = 'pickup_minimum'), 0) as pickup_minimum,
  coalesce((select (value #>> '{}')::numeric from public.site_settings where key = 'delivery_fee'), 0) as delivery_fee,
  coalesce((select accepts_orders from public.store_availability where id), false) as is_open,
  coalesce((select pickup_enabled from public.store_availability where id), false) as pickup_enabled,
  coalesce((select delivery_enabled from public.store_availability where id), false) as delivery_enabled,
  coalesce((select minimum_notice_minutes from public.store_availability where id), 30) as minimum_notice_minutes,
  (select paused_reason from public.store_availability where id) as closed_message;

create or replace function public.create_cash_order(p_order jsonb, p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  created public.orders;
begin
  insert into public.orders (
    order_number,
    confirmation_token,
    idempotency_key,
    status,
    fulfillment_type,
    payment_status,
    payment_method,
    accepted_no_cancellation,
    customer_name,
    customer_email,
    customer_phone,
    address_line1,
    address_line2,
    postal_code,
    city,
    customer_notes,
    subtotal,
    delivery_fee,
    total,
    currency
  )
  values (
    p_order ->> 'order_number',
    (p_order ->> 'confirmation_token')::uuid,
    p_order ->> 'idempotency_key',
    (p_order ->> 'status')::public.order_status,
    (p_order ->> 'fulfillment_type')::public.fulfillment_type,
    (p_order ->> 'payment_status')::public.payment_status,
    p_order ->> 'payment_method',
    coalesce((p_order ->> 'accepted_no_cancellation')::boolean, false),
    p_order ->> 'customer_name',
    p_order ->> 'customer_email',
    p_order ->> 'customer_phone',
    p_order ->> 'address_line1',
    p_order ->> 'address_line2',
    p_order ->> 'postal_code',
    p_order ->> 'city',
    p_order ->> 'customer_notes',
    (p_order ->> 'subtotal')::numeric,
    (p_order ->> 'delivery_fee')::numeric,
    (p_order ->> 'total')::numeric,
    coalesce(p_order ->> 'currency', 'CHF')
  )
  returning * into created;

  insert into public.order_items (
    order_id,
    menu_item_id,
    name,
    quantity,
    unit_price,
    line_total,
    notes
  )
  select
    created.id,
    (item ->> 'menu_item_id')::bigint,
    item ->> 'name',
    (item ->> 'quantity')::integer,
    (item ->> 'unit_price')::numeric,
    (item ->> 'line_total')::numeric,
    item ->> 'notes'
  from jsonb_array_elements(p_items) as item;

  insert into public.order_status_events (order_id, from_status, to_status, note)
  values (created.id, null, created.status, 'Bestellung eingegangen');

  return jsonb_build_object(
    'id', created.id,
    'order_number', created.order_number,
    'confirmation_token', created.confirmation_token,
    'status', created.status,
    'total', created.total
  );
exception
  when unique_violation then
    select * into created
    from public.orders
    where idempotency_key = p_order ->> 'idempotency_key';

    if found then
      return jsonb_build_object(
        'id', created.id,
        'order_number', created.order_number,
        'confirmation_token', created.confirmation_token,
        'status', created.status,
        'total', created.total
      );
    end if;
    raise;
end;
$$;

revoke all on function public.create_cash_order(jsonb, jsonb) from public;
grant execute on function public.create_cash_order(jsonb, jsonb) to service_role;

