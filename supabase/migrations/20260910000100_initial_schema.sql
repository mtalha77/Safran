create table if not exists public.opening_hours (
  weekday smallint primary key check (weekday between 0 and 6),
  day_of_week smallint generated always as (weekday) stored,
  is_closed boolean not null default false,
  lunch_opens time,
  lunch_closes time,
  dinner_opens time,
  dinner_closes time,
  open_time time generated always as (lunch_opens) stored,
  close_time time generated always as (lunch_closes) stored,
  second_open_time time generated always as (dinner_opens) stored,
  second_close_time time generated always as (dinner_closes) stored,
  note text,
  updated_at timestamptz not null default now(),
  constraint opening_hours_lunch_pair check (
    (lunch_opens is null and lunch_closes is null)
    or (lunch_opens is not null and lunch_closes is not null and lunch_opens < lunch_closes)
  ),
  constraint opening_hours_dinner_pair check (
    (dinner_opens is null and dinner_closes is null)
    or (dinner_opens is not null and dinner_closes is not null and dinner_opens < dinner_closes)
  ),
  constraint opening_hours_closed_has_no_times check (
    not is_closed
    or (lunch_opens is null and lunch_closes is null and dinner_opens is null and dinner_closes is null)
  )
);

create table if not exists public.store_availability (
  id boolean primary key default true check (id),
  accepts_orders boolean not null default true,
  pickup_enabled boolean not null default true,
  delivery_enabled boolean not null default true,
  minimum_notice_minutes integer not null default 30 check (minimum_notice_minutes >= 0),
  paused_reason text,
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default (
    to_char(now(), 'MMDD') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 4))
  ),
  confirmation_token uuid not null unique default gen_random_uuid(),
  idempotency_key text unique,
  user_id uuid references auth.users(id) on delete set null,
  status public.order_status not null default 'pending',
  fulfillment_type public.fulfillment_type not null,
  payment_status public.payment_status not null default 'pending',
  payment_method text not null default 'cash',
  payment_provider text,
  payment_reference text,
  accepted_no_cancellation boolean not null default false,
  currency text not null default 'CHF' check (currency = upper(currency) and char_length(currency) = 3),
  subtotal numeric(10,2) not null check (subtotal >= 0),
  delivery_fee numeric(10,2) not null default 0 check (delivery_fee >= 0),
  total numeric(10,2) not null check (total >= 0 and total = subtotal + delivery_fee),
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  address_line1 text,
  address_line2 text,
  postal_code text,
  city text,
  delivery_address jsonb,
  customer_notes text,
  customer_note text generated always as (customer_notes) stored,
  requested_for timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint delivery_address_required check (
    fulfillment_type <> 'delivery'
    or address_line1 is not null
    or (delivery_address is not null and jsonb_typeof(delivery_address) = 'object')
  )
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  menu_item_id bigint references public.menu_items(id) on delete set null,
  item_number integer,
  name text not null,
  item_name text generated always as (name) stored,
  unit_price numeric(10,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(10,2) not null check (line_total >= 0 and line_total = unit_price * quantity),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.order_status_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  from_status public.order_status,
  to_status public.order_status not null,
  changed_by uuid references auth.users(id) on delete set null,
  note text,
  created_at timestamptz not null default now()
);

